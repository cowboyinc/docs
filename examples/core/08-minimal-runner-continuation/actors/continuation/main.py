import json

from cowboy_sdk import actor, deferred, runner, capture, codec, runtime, pure, public


DEFAULT_SOURCE_URL = "https://example.com/health"


@actor
class RunnerContinuation:
    """Minimal async refresh example using the runtime runner FSM."""

    @public(decode="raw")
    def init(self, payload):
        if self.storage.get("initialized"):
            return codec.encode({
                "status": "already_initialized",
                "source_url": self.storage.get("source_url", DEFAULT_SOURCE_URL),
            })
        self.storage["__name__"] = "Minimal Runner Continuation"
        self.storage["__description__"] = "Minimal example of @runner.continuation pattern"
        self.storage["__version__"] = "1.0.0"
        obj = json.loads(payload) if payload else {}
        self.storage["initialized"] = True
        self.storage["source_url"] = str(obj.get("source_url", DEFAULT_SOURCE_URL))
        self.storage["last_request_id"] = 0
        self.storage["status"] = "idle"
        self.storage["last_result"] = {"status": "idle"}
        return codec.encode({
            "status": "initialized",
            "source_url": self.storage["source_url"],
        })

    @public(decode="cbor")
    @deferred  # dispatching the continuation's runner job is an async side effect
    def refresh(self, payload):
        request_id = int(self.storage.get("last_request_id", 0)) + 1
        self.storage["last_request_id"] = request_id
        self.storage["status"] = "pending"
        request = {
            "request_id": request_id,
            "source_url": self.storage.get("source_url", DEFAULT_SOURCE_URL),
        }
        self.storage["last_result"] = {
            "request_id": request_id,
            "status": "pending",
        }
        return self._run_refresh_job(codec.encode(request))

    @runner.continuation
    async def _run_refresh_job(self, payload):
        # The code after `await` becomes part of the generated
        # `_run_refresh_job__resume` state machine. You do not hand-write the
        # actor-class resume method yourself.
        request = codec.decode(payload) if payload else {}
        request_id = int(request.get("request_id", 0))
        source_url = request.get("source_url", DEFAULT_SOURCE_URL)

        ctx = capture()
        ctx.request_id = request_id

        result = await runner.http(
            source_url,
            method="GET",
            timeout_ms=5000,
        )
        return self._finalize_refresh(ctx.request_id, result)

    def _finalize_refresh(self, request_id, result):
        normalized = result.raw
        if not isinstance(normalized, dict):
            raise ValueError("runner continuation: runner.http did not return a JSON object")
        record = {
            "request_id": int(request_id),
            "status": "done",
            "response": normalized,
        }
        self.storage["status"] = "done"
        self.storage["last_result"] = record
        runtime.emit_event("runner_continuation.result", record)
        return codec.encode(record)

    @public(decode="cbor")
    @pure
    def get_status(self, payload):
        response = {
            "status": self.storage.get("status", "idle"),
            "last_request_id": int(self.storage.get("last_request_id", 0)),
            "last_result": self.storage.get("last_result", {"status": "idle"}),
        }
        runtime.emit_event("get_status", response)
        return response


def _get_actor():
    return RunnerContinuation()


def init(payload):
    return _get_actor().init(payload)


def refresh(payload):
    return _get_actor().refresh(payload)


def _run_refresh_job__resume(payload):
    # PVM invokes module-level entrypoints. The actor-class
    # `_run_refresh_job__resume` method is generated by `@runner.continuation`
    # and installed onto the class by `@actor`.
    return _get_actor()._run_refresh_job__resume(payload)


def get_status(payload):
    return _get_actor().get_status(payload)
